export function getMaterial(id: string): Material {
  const m = MATERIALS.find((m) => m.id === id)
  if (!m) throw new Error(`unknown material: ${id}`)
  return m
}

// ชนิดงานที่ตัดสินใจ path (dieline/3D) จากวัสดุ: กล่องพับ / ภาชนะ revolve / ถุงฟิล์ม
export type PackKind = 'box' | 'vessel' | 'pouch'
export const packKind = (m: Material): PackKind =>
  m.foldable ? 'box' : m.form === 'pouch' ? 'pouch' : 'vessel'

// หลอดครีม = ภาชนะ revolve แบบพิเศษ (ฝาเกลียว + ปลายซีลแบน) — นำเสนอเป็นประเภทงานแยกใน UI
export const isTubeMat = (m: Material) => m.form === 'tube'
// สติกเกอร์ไดคัท = งานพิมพ์แบน — วัสดุ sticker-*
export const isStickerMat = (m: Material) => m.id.startsWith('sticker-')
// กระดาษนามบัตรโดยเฉพาะ (card-*) — โชว์เฉพาะงานนามบัตร ไม่ปนกับวัสดุกล่อง
export const isCardMat = (m: Material) => m.id.startsWith('card-')
// กระดาษที่นามบัตรเลือกได้: card-* + กระดาษกล่องเดิม (งานเก่าที่ตั้งไว้ยังเปิดได้)
export const CARD_STOCK_IDS = [...MATERIALS.filter(isCardMat).map((m) => m.id), 'carton-300', 'carton-400', 'kraft-350']
export const DEFAULT_CARD_MAT = 'card-art-matte'
